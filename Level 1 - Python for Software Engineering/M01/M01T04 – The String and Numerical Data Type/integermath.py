# Ask user for three integers
num1 = int(input("Enter the first integer: "))
num2 = int(input("Enter the second integer: "))
num3 = int(input("Enter the third integer: "))

# Calculations and output
print("Sum of all numbers:", num1 + num2 + num3)
print("First number minus second number:", num1 - num2)
print("Third number multiplied by first number:", num3 * num1)
print("Sum of all three numbers divided by third number:", (num1 + num2 + num3) / num3)